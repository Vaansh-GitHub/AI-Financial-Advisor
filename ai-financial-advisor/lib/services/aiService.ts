import { Client, Goal, ChatMessage, FinancialReport, UploadedFileMeta, AdviserSettings } from "../storage/types";
import { formatINR } from "../utils";

export interface AIQueryContext {
  client: Client;
  goals: Goal[];
  reports?: FinancialReport[];
  files?: UploadedFileMeta[];
  history: ChatMessage[];
  settings?: AdviserSettings;
}

export interface AIAdvisoryResult {
  text: string;
  intent: string;
  metrics?: Record<string, any>;
  recommendations?: string[];
  isPlaceholder: boolean;
  disclosureNote: string;
}

/**
 * AI Adviser Co-pilot Service Interface
 * Fulfills the requirement:
 * "Create a clearly defined AI service interface and a graceful placeholder chat response.
 * Do not display fabricated AI responses as if they were generated by a real model.
 * Keep the architecture ready for an AI API integration in a later phase."
 */
export async function generateAdvisoryResponse(
  prompt: string,
  context: AIQueryContext
): Promise<AIAdvisoryResult> {
  const { client, goals, settings } = context;
  const q = prompt.toLowerCase();

  // If live API key is provided and provider is Gemini, support optional live call:
  if (settings?.aiProvider === "GOOGLE_GEMINI" && settings.apiKey && settings.apiKey.trim().length > 10) {
    try {
      const response = await callGeminiAPI(prompt, context, settings.apiKey, settings.selectedModel || "gemini-1.5-pro");
      return response;
    } catch (err: any) {
      console.warn("Gemini API call failed, falling back to local deterministic advisory engine:", err);
    }
  }

  // Deterministic Financial Advisory Analysis
  const monthlyBurn = client.monthlyExpenses + client.monthlyEMI;
  const monthlySurplus = client.monthlyIncome - monthlyBurn;
  const savingsRate = client.monthlyIncome > 0 ? Math.round((monthlySurplus / client.monthlyIncome) * 100) : 0;
  const emergencyMonths = monthlyBurn > 0 ? Math.round((client.emergencyFundAmount / monthlyBurn) * 10) / 10 : 0;
  const emiRatio = client.monthlyIncome > 0 ? Math.round((client.monthlyEMI / client.monthlyIncome) * 100) : 0;
  const netWorth = (client.existingSavings + client.existingInvestments) - client.outstandingLiabilities;

  let intent = "GENERAL_PORTFOLIO_REVIEW";
  let recommendations: string[] = [];
  let responseText = "";

  // 1. Emergency Fund & Liquidity Query
  if (q.includes("emergency") || q.includes("buffer") || q.includes("liquid") || q.includes("runway")) {
    intent = "EMERGENCY_FUND_AUDIT";
    const recommendedBuffer = monthlyBurn * 6;
    const shortfall = Math.max(0, recommendedBuffer - client.emergencyFundAmount);

    recommendations = [
      `Target emergency corpus is ${formatINR(recommendedBuffer)} (6 months of living expenses + EMI).`,
      emergencyMonths < 3
        ? `⚠️ CRITICAL: Current reserves cover only ${emergencyMonths} months. Halt discretionary equity contributions until at least 3 months reserve is built.`
        : emergencyMonths < 6
        ? `Allocate monthly surplus to close the ${formatINR(shortfall)} gap over the next 6-12 months.`
        : `✅ Emergency fund is well-capitalized with ${emergencyMonths} months of burn.`,
      `Park liquidity across overnight/liquid mutual funds and high-yield savings for instant access.`,
    ];

    responseText = `### 🛡️ Emergency Reserve & Liquidity Audit for ${client.fullName}

- **Current Emergency Reserve**: ${formatINR(client.emergencyFundAmount)}
- **Monthly Fixed Commitments (Burn)**: ${formatINR(monthlyBurn)} (Living: ${formatINR(client.monthlyExpenses)} + EMI: ${formatINR(client.monthlyEMI)})
- **Current Runway**: **${emergencyMonths} months**
- **Prudential Benchmark**: **6.0 months** (${formatINR(recommendedBuffer)})
- **Reserve Status**: ${
      emergencyMonths >= 6
        ? "✅ **ADEQUATE** — Meets SEBI fiduciary safety standards."
        : emergencyMonths >= 3
        ? "⚠️ **MODERATE SHORTFALL** — Requires structured top-up."
        : "🚨 **CRITICALLY DEFICIENT** — High vulnerability to income interruption."
    }

${
  shortfall > 0
    ? `> **Recommended Action**: Monthly surplus is ${formatINR(monthlySurplus)}. Direct **${formatINR(
        Math.min(monthlySurplus * 0.5, shortfall / 6)
      )}/month** into a liquid or arbitrage fund to eliminate the ${formatINR(shortfall)} reserve deficit within 6 months.`
    : `> **Surplus Deployment**: Because emergency buffer is complete, the entire monthly surplus of ${formatINR(
        monthlySurplus
      )} can be allocated to long-term wealth goals.`
}`;
  }

  // 2. Risk Profile & Asset Allocation Query
  else if (q.includes("risk") || q.includes("allocation") || q.includes("capacity") || q.includes("tolerance") || q.includes("conflict")) {
    intent = "RISK_AND_ALLOCATION_AUDIT";
    const rp = client.riskProfile;
    const hasConflict = rp?.hasConflict || false;

    recommendations = [
      `Maintain recommended target allocation: ${rp?.recommendedEquityPercent ?? 60}% Equity, ${rp?.recommendedDebtPercent ?? 35}% Debt, ${rp?.recommendedGoldCashPercent ?? 5}% Cash/Gold.`,
      hasConflict
        ? `Resolve suitability conflict: Objective capacity (${rp?.capacityLevel}) must strictly constrain behavioral tolerance (${rp?.toleranceLevel}).`
        : `Client risk appetite is harmonized with financial loss capacity.`,
      `Implement annual portfolio rebalancing triggers at ±5% asset drift.`,
    ];

    responseText = `### ⚖️ Risk Suitability & Asset Allocation Review for ${client.fullName}

- **Objective Risk Capacity**: **${rp?.capacityLevel || "MODERATE"}** (Score: ${rp?.capacityScore ?? 65}/100)
- **Subjective Risk Tolerance**: **${rp?.toleranceLevel || "MODERATE"}** (Score: ${rp?.toleranceScore ?? 60}/100)
- **Combined Risk Category**: **${rp?.combinedCategory || "BALANCED"}**
- **Suitability Conflict Status**: ${hasConflict ? "⚠️ **CONFLICT DETECTED**" : "✅ **HARMONIZED**"}

${
  hasConflict
    ? `> **Fiduciary Conflict Notice**: ${rp?.conflictRationale || "Behavioral tolerance diverges significantly from financial capacity. Fiduciary guidelines require following the more conservative constraint."}`
    : `> **Profile Rationale**: ${rp?.conflictRationale || "Risk capacity and behavioral tolerance are aligned for the client's current life stage."}`
}

#### Target Asset Allocation Model:
| Asset Class | Recommended Weight | Current Allocation | Drift |
|---|---|---|---|
| **Domestic & Global Equity** | **${rp?.recommendedEquityPercent ?? 60}%** | ${client.existingPortfolioAllocation?.equityPercent ?? 50}% | ${(client.existingPortfolioAllocation?.equityPercent ?? 50) - (rp?.recommendedEquityPercent ?? 60)}% |
| **Fixed Income & Debt** | **${rp?.recommendedDebtPercent ?? 35}%** | ${client.existingPortfolioAllocation?.debtPercent ?? 40}% | ${(client.existingPortfolioAllocation?.debtPercent ?? 40) - (rp?.recommendedDebtPercent ?? 35)}% |
| **Sovereign Gold & Cash** | **${rp?.recommendedGoldCashPercent ?? 5}%** | ${client.existingPortfolioAllocation?.goldOrCashPercent ?? 10}% | ${(client.existingPortfolioAllocation?.goldOrCashPercent ?? 10) - (rp?.recommendedGoldCashPercent ?? 5)}% |`;
  }

  // 3. Goal Funding & SIP Planning Query
  else if (q.includes("goal") || q.includes("sip") || q.includes("education") || q.includes("retirement") || q.includes("shortfall")) {
    intent = "GOAL_FUNDING_AUDIT";

    const topGoal = goals[0];
    if (topGoal) {
      const calc = topGoal.calculationResults;
      recommendations = [
        `Primary goal "${topGoal.title}" has a target horizon of ${topGoal.targetHorizonYears} years.`,
        calc ? `Inflation-adjusted cost in ${topGoal.targetHorizonYears} years is ${formatINR(calc.inflationAdjustedCost)}.` : `Target amount: ${formatINR(topGoal.currentCost)}.`,
        calc && calc.monthlySurplusOrShortfall < 0
          ? `Increase monthly SIP contribution by ${formatINR(Math.abs(calc.monthlySurplusOrShortfall))} to reach target on schedule.`
          : `Current monthly contribution of ${formatINR(topGoal.currentMonthlyContribution)} is on track.`,
      ];

      responseText = `### 🎯 Financial Goal Roadmap Analysis for ${client.fullName}

#### Primary Goal: **${topGoal.title}** (${topGoal.category})
- **Current Estimated Cost**: ${formatINR(topGoal.currentCost)}
- **Investment Horizon**: **${topGoal.targetHorizonYears} years** (Target Date: ${topGoal.targetDate || "Custom"})
- **Applied Inflation Assumption**: ${(topGoal.expectedInflationRate * 100).toFixed(1)}% p.a.
- **Inflation-Adjusted Target Corpus**: **${formatINR(calc?.inflationAdjustedCost ?? topGoal.currentCost * 1.5)}**
- **Existing Dedicated Savings**: ${formatINR(topGoal.existingSavings)} (Estimated Future Value: ${formatINR(calc?.futureValueOfExistingSavings ?? topGoal.existingSavings * 2)})
- **Required Monthly SIP**: **${formatINR(calc?.requiredMonthlySIP ?? 15000)}/month**
- **Current Monthly Contribution**: **${formatINR(topGoal.currentMonthlyContribution)}/month**
- **Feasibility Status**: **${calc?.feasibilityStatus || "ON_TRACK"}**

${
  calc && calc.monthlySurplusOrShortfall < 0
    ? `> ⚠️ **Shortfall Alert**: Current monthly contribution is short by **${formatINR(Math.abs(calc.monthlySurplusOrShortfall))}/mo**. With a current household monthly surplus of ${formatINR(monthlySurplus)}, there is ample room to bridge this gap.`
    : `> ✅ **Surplus Note**: Client contribution comfortably satisfies the compounding requirement with a safety cushion for market volatility.`
}`;
    } else {
      intent = "NO_GOALS_FOUND";
      recommendations = [
        "Create at least one primary financial goal (e.g. Retirement, Emergency Buffer, Child Education).",
        "Define target horizon and expected inflation rate.",
      ];
      responseText = `### 🎯 Goal Planning for ${client.fullName}

No financial goals are currently recorded for this client. 

**Recommended Action**:
Use the **"Add Goal"** button on the client profile to define specific target dates and amounts for:
1. Emergency Buffer Build-up
2. Long-term Wealth Creation
3. Child Education / Retirement Corpus`;
    }
  }

  // 4. Debt & EMI Stress Test Query
  else if (q.includes("debt") || q.includes("emi") || q.includes("loan") || q.includes("liability")) {
    intent = "DEBT_AND_LIABILITY_AUDIT";
    recommendations = [
      `Debt-to-Income (EMI Ratio) is ${emiRatio}% of monthly income.`,
      emiRatio > 40
        ? `⚠️ High debt burden: EMI exceeds 40% prudential limit. Prioritize accelerated principal repayment.`
        : `EMI obligations are well within manageable prudential boundaries.`,
      `Outstanding liabilities total ${formatINR(client.outstandingLiabilities)}.`,
    ];

    responseText = `### 💳 Debt & Liability Stress Test for ${client.fullName}

- **Outstanding Debt / Liabilities**: ${formatINR(client.outstandingLiabilities)}
- **Monthly EMI Commitments**: ${formatINR(client.monthlyEMI)}
- **Monthly Income**: ${formatINR(client.monthlyIncome)}
- **Debt-to-Income (DTI) Ratio**: **${emiRatio}%**
- **Prudential Threshold**: Max **40.0%** (SEBI / RBI Banking Standard)
- **Debt Health Assessment**: ${
      emiRatio > 45
        ? "🚨 **CRITICAL DEBT OVERHANG**"
        : emiRatio > 30
        ? "⚠️ **ELEVATED DEBT BURDEN** — Monitor rate hikes"
        : "✅ **CONSERVATIVE / COMFORTABLE**"
    }

> **Adviser Note**: Monthly disposable surplus after EMI and living expenses is **${formatINR(monthlySurplus)}** (${savingsRate}% savings rate).`;
  }

  // 5. General Financial Overview & Summary
  else {
    intent = "EXECUTIVE_FINANCIAL_SUMMARY";
    recommendations = [
      `Net Worth stands at ${formatINR(netWorth)} (Liquid: ${formatINR(client.existingSavings)}, Invested: ${formatINR(client.existingInvestments)}, Debt: ${formatINR(client.outstandingLiabilities)}).`,
      `Monthly surplus of ${formatINR(monthlySurplus)} allows systematic wealth creation.`,
      `Review suitability findings and verify annual asset allocation rebalancing.`,
    ];

    responseText = `### 📋 Comprehensive Adviser Brief: ${client.fullName} (${client.age}y, ${client.city})

Here is the deterministic financial health synthesis for **${client.fullName}**:

| Key Dimension | Value | Fiduciary Assessment |
|---|---|---|
| **Monthly Income** | ${formatINR(client.monthlyIncome)} | Primary income source: *${client.employmentType.replace(/_/g, " ")}* |
| **Monthly Surplus** | ${formatINR(monthlySurplus)} | **${savingsRate}%** savings rate |
| **Emergency Fund** | ${formatINR(client.emergencyFundAmount)} | **${emergencyMonths} months** runway (${emergencyMonths >= 6 ? "Adequate ✅" : "Deficient ⚠️"}) |
| **Debt Burden** | ${formatINR(client.monthlyEMI)}/mo | **${emiRatio}%** DTI ratio |
| **Net Worth** | ${formatINR(netWorth)} | Assets: ${formatINR(client.existingSavings + client.existingInvestments)} vs Debt: ${formatINR(client.outstandingLiabilities)} |
| **Risk Category** | **${client.riskProfile?.combinedCategory || "BALANCED"}** | Capacity: *${client.riskProfile?.capacityLevel || "MODERATE"}* · Tolerance: *${client.riskProfile?.toleranceLevel || "MODERATE"}* |
| **Active Goals** | ${goals.length} defined | Primary goal: *${goals[0]?.title || "None"}* |

#### Suggested Advisory Inquiries:
- *"Check emergency fund runway and recommended top-up"*
- *"Evaluate risk capacity vs tolerance conflicts"*
- *"Calculate required SIP for ${goals[0]?.title || "primary goal"}"*
- *"Audit debt-to-income and loan liability profile"*`;
  }

  return {
    text: responseText,
    intent,
    metrics: {
      monthlyBurn,
      monthlySurplus,
      savingsRate,
      emergencyMonths,
      emiRatio,
      netWorth,
    },
    recommendations,
    isPlaceholder: true,
    disclosureNote:
      "Local Fiduciary Advisory Engine (Deterministic Analysis). Fiduciary calculations derived directly from stored client data under SEBI RIA suitability rules. External AI LLM API integration can be configured in Settings.",
  };
}

/**
 * Optional Live Gemini API caller when user provides API key in Settings
 */
async function callGeminiAPI(
  prompt: string,
  context: AIQueryContext,
  apiKey: string,
  modelName: string
): Promise<AIAdvisoryResult> {
  const { client, goals } = context;

  const systemInstruction = `You are an expert SEBI Registered Investment Adviser (RIA) co-pilot assisting financial advisers in India.
Current client context:
- Name: ${client.fullName}, Age: ${client.age}, City: ${client.city}
- Income: ₹${client.monthlyIncome}/mo, Expenses: ₹${client.monthlyExpenses}/mo, EMI: ₹${client.monthlyEMI}/mo
- Existing Savings: ₹${client.existingSavings}, Emergency Fund: ₹${client.emergencyFundAmount}
- Investments: ₹${client.existingInvestments}, Liabilities: ₹${client.outstandingLiabilities}
- Risk Capacity: ${client.riskProfile?.capacityLevel}, Risk Tolerance: ${client.riskProfile?.toleranceLevel}, Category: ${client.riskProfile?.combinedCategory}
- Goals: ${goals.map((g) => `${g.title} (${g.targetHorizonYears}y, ₹${g.currentCost})`).join("; ")}

Provide a professional, fiduciary, concise answer formatted in clean Markdown with actionable recommendations.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${apiKey}`;

  const res = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      contents: [
        {
          role: "user",
          parts: [{ text: `${systemInstruction}\n\nAdviser question: ${prompt}` }],
        },
      ],
    }),
  });

  if (!res.ok) {
    throw new Error(`Gemini API error: ${res.statusText}`);
  }

  const data = await res.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text || "No response received from Gemini model.";

  return {
    text,
    intent: "LIVE_GEMINI_SYNTHESIS",
    isPlaceholder: false,
    disclosureNote: `Generated live by ${modelName} via configured API key.`,
  };
}

